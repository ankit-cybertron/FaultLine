#!/usr/bin/env bash
# ==============================================================================
# FaultLine — AWS EC2 Production Deployment Script
# Triggered via AWS Systems Manager (SSM) Run Command.
# Idempotent, safe, and zero-downtime deployment for single-EC2 architecture.
# ==============================================================================

set -euo pipefail

APP_DIR="${APP_DIR:-/opt/faultline}"
REPO_URL="${REPO_URL:-https://github.com/ankit-cybertron/FaultLine.git}"
TARGET_COMMIT="${1:-main}"
AWS_REGION="${AWS_REGION:-us-east-1}"
HEALTH_URL="http://127.0.0.1:8000/health"
MAX_HEALTH_ATTEMPTS=24
HEALTH_INTERVAL=5

log() {
  echo "[$(date +'%Y-%m-%d %H:%M:%S')] $*"
}

log "=== Starting FaultLine Deployment ==="
log "Target directory: $APP_DIR"
log "Target commit/branch: $TARGET_COMMIT"

# 1. Check prerequisites
for cmd in git docker curl; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    log "ERROR: Required command '$cmd' is not installed or not in PATH."
    exit 1
  fi
done

# Check Docker Compose (plugin or standalone)
if docker compose version >/dev/null 2>&1; then
  COMPOSE_CMD="docker compose"
elif command -v docker-compose >/dev/null 2>&1; then
  COMPOSE_CMD="docker-compose"
else
  log "ERROR: Neither 'docker compose' nor 'docker-compose' is available."
  exit 1
fi
log "Using Docker Compose command: $COMPOSE_CMD"

# 2. Prepare deployment directory
if [ ! -d "$APP_DIR/.git" ]; then
  log "Repository not found in $APP_DIR. Cloning from $REPO_URL..."
  mkdir -p "$(dirname "$APP_DIR")"
  git clone "$REPO_URL" "$APP_DIR"
  cd "$APP_DIR"
else
  cd "$APP_DIR"
  log "Existing repository found in $APP_DIR. Fetching latest changes..."
  git remote set-url origin "$REPO_URL" || true
  git fetch --all --tags --prune
fi

# 3. Check out target commit cleanly without disturbing local data directories
log "Checking out target commit: $TARGET_COMMIT"
git checkout -f "$TARGET_COMMIT"
CURRENT_SHA=$(git rev-parse HEAD)
log "Checked out commit SHA: $CURRENT_SHA"

# 4. Configure runtime environment securely
log "Configuring runtime environment..."
mkdir -p data/otel data/runs eval/results .cache/llm
touch .env
chmod 600 .env

# Retrieve GROQ_API_KEY securely from AWS SSM Parameter Store if available
GROQ_KEY_FETCHED=""
if command -v aws >/dev/null 2>&1; then
  log "Checking AWS SSM Parameter Store for /faultline/GROQ_API_KEY..."
  PARAM_VALUE=$(aws ssm get-parameter \
    --name "/faultline/GROQ_API_KEY" \
    --with-decryption \
    --query "Parameter.Value" \
    --output text \
    --region "$AWS_REGION" 2>/dev/null || true)
  if [ -n "$PARAM_VALUE" ] && [ "$PARAM_VALUE" != "None" ]; then
    GROQ_KEY_FETCHED="$PARAM_VALUE"
    log "Successfully retrieved GROQ_API_KEY from AWS SSM Parameter Store."
  fi
fi

# Determine active GROQ_API_KEY
if [ -n "$GROQ_KEY_FETCHED" ]; then
  GROQ_API_KEY_FINAL="$GROQ_KEY_FETCHED"
elif grep -q "^GROQ_API_KEY=" .env && [ -n "$(grep "^GROQ_API_KEY=" .env | cut -d= -f2-)" ]; then
  log "Using existing GROQ_API_KEY from .env file."
  GROQ_API_KEY_FINAL=$(grep "^GROQ_API_KEY=" .env | cut -d= -f2-)
else
  log "WARNING: GROQ_API_KEY is not configured in SSM Parameter Store or .env."
  log "The agent will operate in demo/fallback mode unless a key is provided."
  GROQ_API_KEY_FINAL=""
fi

# Assemble .env securely
cat <<EOF > .env
# Auto-generated by FaultLine deployment script
GROQ_API_KEY=${GROQ_API_KEY_FINAL}
FALKORDB_HOST=falkordb
FALKORDB_PORT=6379
INVESTIGATOR_MODEL=llama-3.3-70b-versatile
JUDGE_MODEL=llama-3.1-8b-instant
GRAPH_TRAIL=runs_trail
GRAPH_DEMO=runs_demo
SLICE_DEPTH=8
CACHE_DIR=.cache/llm
MAX_INPUT_TOKENS=6000
EOF
chmod 600 .env
log "Runtime .env file written with restricted permissions (0600)."

# 5. Build and launch containers
log "Building Docker images..."
$COMPOSE_CMD build

log "Starting containers with Docker Compose..."
# We use 'up -d' to recreate only updated containers and preserve named volume 'falkordb_data'
$COMPOSE_CMD up -d

# 6. Verify Health Endpoint
log "Waiting for application to become healthy at $HEALTH_URL..."
ATTEMPT=1
HEALTHY=0

while [ $ATTEMPT -le $MAX_HEALTH_ATTEMPTS ]; do
  log "Healthcheck attempt $ATTEMPT/$MAX_HEALTH_ATTEMPTS..."
  HTTP_STATUS=$(curl -s -o /dev/null -w "%{http_code}" "$HEALTH_URL" 2>/dev/null || echo "000")
  if [ "$HTTP_STATUS" = "200" ]; then
    HEALTH_RESP=$(curl -s "$HEALTH_URL" 2>/dev/null || echo "{}")
    log "Healthcheck PASSED (HTTP 200). Response: $HEALTH_RESP"
    HEALTHY=1
    break
  fi
  sleep $HEALTH_INTERVAL
  ATTEMPT=$((ATTEMPT + 1))
done

if [ $HEALTHY -ne 1 ]; then
  log "ERROR: Healthcheck failed after $MAX_HEALTH_ATTEMPTS attempts."
  log "=== Container Status ==="
  $COMPOSE_CMD ps || true
  log "=== Recent API Container Logs ==="
  $COMPOSE_CMD logs --tail=60 api || true
  log "=== Recent FalkorDB Container Logs ==="
  $COMPOSE_CMD logs --tail=40 falkordb || true
  exit 1
fi

log "=== Active Containers ==="
$COMPOSE_CMD ps

# 7. Clean up dangling images to prevent disk exhaustion on t3.small
log "Cleaning up old dangling images..."
docker image prune -f >/dev/null 2>&1 || true

log "=== Deployment of commit $CURRENT_SHA Completed Successfully! ==="
exit 0
