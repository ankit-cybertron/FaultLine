            "class CausalNode:\n",
            "    \"\"\"A causal value or execution node tracking predecessors (_prev) and operation (_op).\"\"\"\n",
            "    def __init__(self, data, _children=(), _op='', label='', kind='value', grad=0.0):\n",
            "        self.data = data\n",
            "        self.grad = grad\n",
            "        self._prev = set(_children)\n",
            "        self._op = _op\n",
            "        self.label = label or str(data)[:25]\n",
            "        self.kind = kind\n",
            "\n",
            "    def __repr__(self):\n",
            "        return f\"CausalNode(label={self.label!r}, op={self._op!r}, data={str(self.data)[:30]!r})\"\n",
            "\n",
            "    # Numeric operator overloading for math tracing\n",
            "    def __add__(self, other):\n",
            "        other = other if isinstance(other, CausalNode) else CausalNode(other, label=str(other))\n",
            "        return CausalNode(self.data + other.data, (self, other), _op='+', label=f\"{self.label}+{other.label}\")\n",
            "\n",
            "    def __mul__(self, other):\n",
            "        other = other if isinstance(other, CausalNode) else CausalNode(other, label=str(other))\n",
            "        return CausalNode(self.data * other.data, (self, other), _op='*', label=f\"{self.label}*{other.label}\")\n",
            "\n",
            "\n",
            "def trace(root):\n",
            "    \"\"\"Collect all nodes and directed edges by traversing _prev backwards.\"\"\"\n",
            "    nodes, edges = set(), set()\n",
            "    def build(v):\n",
            "        if v not in nodes:\n",
            "            nodes.add(v)\n",
            "            for child in v._prev:\n",
            "                edges.add((child, v))\n",
            "                build(child)\n",
            "    build(root)\n",
            "    return nodes, edges\n",
            "\n",
            "\n",
            "def draw_dot(root, format='svg', rankdir='LR'):\n",
            "    \"\"\"\n",
            "    format: png | svg | ...\n",
            "    rankdir: TB (top to bottom graph) | LR (left to right)\n",
            "    \"\"\"\n",
            "    assert rankdir in ['LR', 'TB']\n",
            "    nodes, edges = trace(root)\n",
            "    dot = Digraph(format=format, graph_attr={'rankdir': rankdir, 'bgcolor': '#0d1117'})\n",
            "\n",
            "    kind_colors = {\n",
            "        'input': '#1f6feb',\n",
            "        'context': '#8957e5',\n",
            "        'router': '#d29922',\n",
